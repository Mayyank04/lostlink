import { NextResponse } from 'next/server';
import { prisma } from '@/lib/db';
import { requireAuth, errorResponse } from '@/lib/auth/tenant';
import { HandoverStatus, UserRole } from '@prisma/client';
import { generateOTP, generateQrToken, hashToken } from '@/lib/handover/crypto';

export const dynamic = 'force-dynamic';

export async function POST(
  req: Request,
  { params }: { params: { id: string } }
) {
  try {
    const user = await requireAuth(req);
    const { id } = params;

    const challenge = await prisma.handoverChallenge.findFirst({
      where: {
        OR: [{ id }, { claimId: id }],
      },
      include: {
        claim: {
          include: {
            claimant: true,
            item: { include: { college: true } },
          },
        },
      },
    });

    if (!challenge) {
      return NextResponse.json({ error: 'Handover challenge not found' }, { status: 404 });
    }

    if (challenge.status === HandoverStatus.CONFIRMED) {
      return NextResponse.json(
        { error: 'Cannot regenerate a challenge that has already been confirmed' },
        { status: 400 }
      );
    }

    const isClaimant = challenge.claim.claimantId === user.id;
    const isFinder = challenge.claim.item.reporterId === user.id;
    const isCollegeAdmin =
      user.role === UserRole.PLATFORM_ADMIN ||
      user.memberships.some(
        (m) =>
          m.collegeId === challenge.claim.item.collegeId &&
          (user.role === UserRole.COLLEGE_ADMIN || user.role === UserRole.COLLEGE_MODERATOR)
      );

    if (!isClaimant && !isFinder && !isCollegeAdmin) {
      return NextResponse.json(
        { error: 'You are not authorized to regenerate this handover challenge' },
        { status: 403 }
      );
    }

    const rawOtp = generateOTP();
    const rawQrToken = generateQrToken();
    const codeHash = hashToken(rawOtp);
    const qrTokenHash = hashToken(rawQrToken);
    const expiresAt = new Date(Date.now() + 24 * 60 * 60 * 1000);

    const updated = await prisma.$transaction(async (tx) => {
      const c = await tx.handoverChallenge.update({
        where: { id: challenge.id },
        data: {
          codeHash,
          qrTokenHash,
          status: HandoverStatus.PENDING,
          expiresAt,
          confirmedAt: null,
          confirmedByUserId: null,
        },
      });

      await tx.claimStatusHistory.create({
        data: {
          claimId: challenge.claimId,
          fromStatus: challenge.claim.status,
          toStatus: challenge.claim.status,
          actorId: user.id,
          notes: 'Handover challenge code regenerated by user.',
        },
      });

      await tx.auditLog.create({
        data: {
          actorId: user.id,
          collegeId: challenge.claim.item.collegeId,
          action: 'HANDOVER_CHALLENGE_REGENERATED',
          resourceType: 'HANDOVER_CHALLENGE',
          resourceId: challenge.id,
        },
      });

      return c;
    });

    return NextResponse.json({
      message: 'New handover verification code generated',
      handover: {
        id: updated.id,
        claimId: updated.claimId,
        status: updated.status,
        expiresAt: updated.expiresAt.toISOString(),
        exchangeOtp: rawOtp,
        qrToken: rawQrToken,
      },
    });
  } catch (error) {
    return errorResponse(error);
  }
}

